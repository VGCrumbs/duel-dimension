    /** One cell of {@link #LIMIT_BADGES} is half the file on each axis. */
    private static final float LIMIT_CELL = 0.5F;

    /**
     * Where a banlist limit's badge sits in {@link #LIMIT_BADGES}, or null.
     *
     * @param limit copies the list allows: 0 forbidden, 1 limited, 2 semi-limited
     * @return {@code {u0, v0, u1, v1}}, or null when the card is unrestricted
     *         and has no badge at all
     */
    public static float[] limitCell(int limit)
    {
        // Three, not four. A card the list does not mention is unlimited, and
        // Banlist.limitFor returns UNLIMITED for it -- so "no badge" is the
        // common answer and has to be an answer rather than a fall-through.
        if(limit < 0 || limit >= Banlist.UNLIMITED)
        {
            return null;
        }
        // Column then row, which is the order the file is laid out in: 0 and 1
        // across the top, 2 beginning the second row.
        float u0 = (limit % 2) * LIMIT_CELL;
        float v0 = (limit / 2) * LIMIT_CELL;
        return new float[] {u0, v0, u0 + LIMIT_CELL, v0 + LIMIT_CELL};
    }
