    /**
     * The mod already ships an icon per duel action for its manual mode;
     * reusing them gives the command menu a symbol beside every entry.
     * Reposition has two icons because the action differs by current position.
     */
    public static ResourceLocation commandIcon(int command, boolean faceDown, boolean attackPosition)
    {
        // THE NDS GAME'S OWN BUTTONS, not the mod's own icons and not EDOPro's.
        //
        // World Championship 2011 answers a selected card with a row of picture
        // buttons, and these are those pictures -- extracted from `duel2d.pac`,
        // documented in `textures/gui/duel/cmd/CREDITS.md` beside them. EDOPro
        // has no art to take here at all: its menu is text (ShowMenu builds
        // plain buttons), which is why this used to be a mixture of two of its
        // field markers and nine icons drawn for this mod.
        //
        // Each file is 32x64 -- two states, idle over selected. Sampling is the
        // caller's job through `COMMAND_ICON_*`; this only says which file.
        //
        // The two REPOS captions are two different buttons in the original, and
        // that is the one place a command maps to more than one picture: a card
        // that would go to attack shows the upright card, one that would go to
        // defence shows it lying down. Measured off the icons rather than
        // assumed -- see the vault note.
        String name = switch(command)
        {
            case de.cas_ual_ty.dueldimension.ocg.prompt.CardCommands.COMMAND_ACTIVATE -> "activate";
            case de.cas_ual_ty.dueldimension.ocg.prompt.CardCommands.COMMAND_SUMMON -> "summon";
            case de.cas_ual_ty.dueldimension.ocg.prompt.CardCommands.COMMAND_SPSUMMON -> "special_summon";
            case de.cas_ual_ty.dueldimension.ocg.prompt.CardCommands.COMMAND_MSET -> "set_monster";
            case de.cas_ual_ty.dueldimension.ocg.prompt.CardCommands.COMMAND_SSET -> "set_spell";
            // A face-down card flipping up is the flip-summon button; a face-up
            // one is changing posture, and which way decides the picture.
            case de.cas_ual_ty.dueldimension.ocg.prompt.CardCommands.COMMAND_REPOS ->
                faceDown ? "flip_summon" : attackPosition ? "to_defence" : "to_attack";
            case de.cas_ual_ty.dueldimension.ocg.prompt.CardCommands.COMMAND_ATTACK -> "attack";
            case de.cas_ual_ty.dueldimension.ocg.prompt.CardCommands.COMMAND_LIST -> "list";
            default -> null;
        };
        return name == null ? null
            : ResourceLocation.fromNamespaceAndPath(DuelDimension.MOD_ID,
                "textures/gui/duel/cmd/" + name + ".png");
    }

